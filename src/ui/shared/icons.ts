export function resolveIcon(
  name: string | undefined,
  fallback: LucideIcon = ScrollText,
): LucideIcon {
  return (name ? ICONS.get(name) : undefined) ?? fallback;
}

interface IconProps {
  name: string | undefined;
  size?: number;
  fallback?: LucideIcon;
  strokeWidth?: number;
}

/** Icona decorativa (aria-hidden) da nome-stringa. */
export function Icon({ name, size = 20, fallback, strokeWidth = 2.5 }: IconProps): ReactElement {
  return createElement(resolveIcon(name, fallback), {
    size,
    strokeWidth,
    'aria-hidden': true,
    focusable: false,
  });
}
